//! VLM 分级图表理解提示词（REQ-MM-005）。
//!
//! 将图片内容按类型分级提取为可检索的结构化文本：
//! - Level 1 表格 → Markdown 表格
//! - Level 2 流程图/甘特图 → Mermaid 语法
//! - Level 3 数据图表 → CSV 数据点 + 趋势描述 + 误差标注
//! - Level 4 示意图/照片 → 简洁文字描述
//! - 数学公式 → LaTeX（`$...$` / `$$...$$`）
//!
//! 集中定义于本模块，供 `MultimodalPdfLoader`（loader.rs）与
//! `ImportService`（import.rs）共用，消除重复（铁律三）。

/// VLM 分级图表理解系统提示（REQ-MM-005）。
///
/// 传入 `VisionLanguageModel::describe_image` 的 `prompt` 参数，
/// 引导 VLM 按内容类型执行 4 级精度提取策略。
///
/// # 设计原则
/// - **数据优先**：Level 3 从"描述图表"升级为"提取图表数据"（CSV），
///   使数据图表中的具体数值进入分块→嵌入→存储链路，可被 RAG 检索。
/// - **幻觉标注**：VLM 对密集数据图表的提取精度有限，提取结果须标注误差提示，
///   定位为"AI 辅助提取，人类核对原文"。
/// - **公式还原**：数学公式以 LaTeX 提取，避免 OCR 乱码。
///
/// 调研依据：Salesforce CogAlign（VLM 图表理解增强）、ChartHal（VLM 幻觉评估）、
/// Marker（PDF→Markdown 公式 LaTeX 还原）、Nougat（Meta 学术 PDF 公式提取）。
pub const VLM_TIERED_PROMPT: &str = "\
你是一个文档图片理解助手。请先判断图片的内容类型，再按对应的精度等级提取结构化文本：\n\
\n\
【Level 1 — 表格】\n\
完整提取为 Markdown 表格语法，保留所有行列数据，不要遗漏任何单元格。\n\
\n\
【Level 2 — 流程图 / 甘特图 / 架构图】\n\
转换为 Mermaid 语法（flowchart / gantt / graph），保留节点关系与流程方向。\n\
\n\
【Level 3 — 数据图表（散点图 / 柱状图 / 折线图 / 饼图 / 热力图等）】\n\
这是核心提取任务，须从「描述图表」升级为「提取图表数据」：\n\
1. 判断图表类型（如「柱状图」、「折线图」）\n\
2. 提取坐标轴标签（X 轴名称、Y 轴名称、单位）\n\
3. 提取数据系列名称（如「实验组」、「对照组」）\n\
4. 提取关键数值点，以 CSV 格式输出（第一行为表头，后续每行一个数据点）\n\
5. 附带趋势描述（如「X 与 Y 呈正相关」、「峰值出现在 3 月」）\n\
\n\
输出示例：\n\
图表类型：柱状图\n\
坐标轴：X=月份, Y=销售额（万元）\n\
数据系列：销售额\n\
数据（CSV）：\n\
月份,销售额\n\
1月,120\n\
2月,150\n\
3月,180\n\
趋势：销售额逐月上升\n\
以下数据由 AI 视觉提取，可能存在误差，请核对原文\n\
\n\
【Level 4 — 示意图 / 照片 / 插图】\n\
简洁文字描述图片内容与用途，无需提取数据。\n\
\n\
【数学公式】\n\
如果图片包含数学公式，使用 LaTeX 格式提取：行内公式用 $...$，行间公式用 $$...$$。\n\
不要输出公式截图的 OCR 乱码，须还原为可渲染的 LaTeX 源码。\n\
\n\
【纯文字图片】\n\
直接提取图片中的文字内容，保持原文格式。\n\
\n\
请仅输出提取的结构化文本，不要添加额外解释。";
